/**
 * Короткие вертикальные видео («сториз») для главной страницы.
 *
 * Файлы лежат в `public/videos/stories/` и, как вся медиатека проекта, в git не
 * хранятся (см. `.gitignore`) — они попадают в `dist-dafedorov/videos/stories/`
 * при сборке и выкладываются вместе с сайтом.
 *
 * Как готовились: врач дал 24 вертикальных ролика общим весом 3.9 ГБ (средний —
 * 167 МБ и 54 секунды, то есть для веба непригодно). Из них отобраны шесть,
 * пять обрезаны до 15 секунд и пережаты в 720×1280 при ~1 Мбит/с. Субтитры
 * вшиты в кадр, поэтому ролики осмысленны без звука; звук при этом сохранён,
 * и его можно включить в просмотре. С тех пор лента выросла до семи кружков:
 * два ролика заменены/добавлены позже (см. `evlk-talk` и `rare-surgery`).
 *
 * ⚠️ Первый кружок (`remove-veins`) — исключение: владелец попросил поставить
 * этот ролик ЦЕЛИКОМ, поэтому он не обрезан (20.3 с) и лежит в 720×1280 при
 * ~0.7 Мбит/с. Исходник от врача был в HEVC (H.265), и его пришлось пережать в
 * H.264: HEVC в `<video>` не играет в Firefox и в Chrome без аппаратной
 * поддержки — ролик бы просто не запускался.
 *
 * ⚠️ Всем роликам нужен `-movflags +faststart` (moov перед mdat). Без него
 * браузер сначала тянет хвост файла за индексом — лишний круг и задержка
 * старта. У роликов блога и докладов faststart есть, у сториз его не было.
 *
 * ⚠️ Громкость всех роликов выровнена по первому кружку (−11.4 LUFS).
 * Исходники от ArtVe пришли с разбросом 14 дБ: первый ролик −11.4 LUFS, второй
 * −25.2 — при переключении между кружками это слышалось как «прыжок» громкости.
 * Выравнивание сделано БЕЗ перекодирования картинки (`-c:v copy`, меняется
 * только звуковая дорожка), поэтому качество видео осталось исходным. Держать
 * этот уровень при замене роликов: иначе разница вернётся.
 *
 * ⚠️ `rare-surgery` (2026-10-18) — третий ролик от АртВе, пришедший уже готовым
 * для веба (720×1280 H.264, 13.4 с). Картинка скопирована байт в байт
 * (`-c:v copy`, md5 дорожки совпадает с исходником), звук поднят на 4 дБ:
 * исходник был −14.5 LUFS при пике +0.57 dBTP, то есть уже с перегрузом, поэтому
 * громкость поднималась через ограничитель (alimiter, потолок 0.841) — иначе
 * пики ушли бы в клиппинг. Итог −11.6 LUFS, −1.07 dBTP. Постер снят на 7-й
 * секунде со сдвигом обрезки вниз (`crop=540:960:90:320`, это максимум для
 * 1280 px): вшитый текст занимает верх кадра, и при сдвиге вниз в центральный
 * квадрат кружка попадают только руки хирурга и турникет на ноге. Проверено
 * рендером настоящей обрезки 62 px, а не на глаз по полному кадру.
 *
 * ⚠️ `evlk-talk` (2026-10-10) — второй случай, когда перекодировать картинку не
 * понадобилось: источник пришёл от АртВе уже в 720×1280 H.264 (WhatsApp Video),
 * то есть сразу пригодным для веба. Видеодорожка скопирована БАЙТ В БАЙТ
 * (`-c:v copy`; md5 дорожки совпадает с исходником), а звуку подняли уровень на
 * 3.3 дБ — с −14.1 до общих −11.4 LUFS. Постер снят на 9-й секунде со сдвигом
 * обрезки вверх (`crop=540:960:90:0`): в центральном квадрате — лица врача и
 * ассистента, а вшитые субтитры в кружок не попадают (в 62 px они нечитаемы).
 */

