-- Краткое имя записи справочника перестало быть коротким.
--
-- В шаблоне истории болезни («Шаблон ИБ 2026_10.docx») назначения записаны
-- готовыми фразами: самое длинное — 650 знаков. Колонка была VARCHAR(500),
-- и сервер обрезал бы хвост рецепта молча: врач увидел бы в базе правдоподобный,
-- но неполный текст.
--
-- Почему VARCHAR(2000), а не TEXT. 23.10.2026 смена типа на TEXT упала на
-- живой базе с ошибкой #1215 «Cannot add foreign key constraint». Причина:
-- смена типа на TEXT перестраивает таблицу целиком, и при перестройке MySQL
-- заново создаёт внешний ключ dictionary_entries.doctor_id → doctors.id —
-- а он в этой базе не воссоздаётся. Удлинение VARCHAR с 500 до 2000 делается
-- на месте, без перестройки таблицы, и внешнего ключа не касается.
--
-- 2000 знаков с запасом покрывают шаблон (максимум 650) и совпадают
-- с ограничением в api/index.php.
--
-- Повторный запуск безопасен: MODIFY в то же самое определение ничего не меняет.

ALTER TABLE dictionary_entries
  MODIFY COLUMN short_text VARCHAR(2000) NOT NULL;
